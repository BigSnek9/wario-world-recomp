// A small INI editor that keeps every other section, key and comment as it is. Keys match case-
// insensitively (Dolphin reads them that way) and keep their existing spelling.
class Ini {
 public:
  explicit Ini(fs::path path) : path_(std::move(path)) {
    if (const auto data = ReadFileBytes(path_)) {
      std::string text = *data;
      if (text.rfind("\xEF\xBB\xBF", 0) == 0) text.erase(0, 3);
      std::istringstream in(text);
      std::string line;
      while (std::getline(in, line)) {
        if (!line.empty() && line.back() == '\r') line.pop_back();
        lines_.push_back(line);
      }
    }
  }
  bool Exists() const { return fs::exists(path_); }
  void Set(const std::string& section, const std::string& key, const std::string& value) {
    int start = FindSection(section);
    if (start < 0) {
      while (!lines_.empty() && Trim(lines_.back()).empty()) lines_.pop_back();
      if (!lines_.empty()) lines_.push_back("");
      lines_.push_back("[" + section + "]");
      lines_.push_back(key + " = " + value);
      return;
    }
    std::size_t end = start + 1, lastContent = start;
    for (; end < lines_.size(); ++end) {
      const std::string t = Trim(lines_[end]);
      if (!t.empty() && t[0] == '[') break;
      if (!t.empty()) lastContent = end;
      const auto eq = t.find('=');
      if (eq == std::string::npos || t[0] == '#' || t[0] == ';') continue;
      const std::string name = Trim(t.substr(0, eq));
      if (Lower(name) == Lower(key)) {
        lines_[end] = name + " = " + value;
        return;
      }
    }
    lines_.insert(lines_.begin() + lastContent + 1, key + " = " + value);
  }
  bool Save() const {
    std::string text;
    for (const auto& line : lines_) text += line + "\r\n";
    return WriteFileBytes(path_, text);
  }

 private:
  int FindSection(const std::string& section) const {
    for (std::size_t i = 0; i < lines_.size(); ++i) {
      const std::string t = Trim(lines_[i]);
      if (t.size() >= 2 && t.front() == '[' && t.back() == ']' && Lower(t.substr(1, t.size() - 2)) == Lower(section))
        return int(i);
    }
    return -1;
  }
  fs::path path_;
  std::vector<std::string> lines_;
};

bool SetIni(const fs::path& path, const std::vector<std::array<std::string, 3>>& values) {
  Ini ini(path);
  for (const auto& [section, key, value] : values) ini.Set(section, key, value);
  return ini.Save();
}

// The in-game menu's settings (<user>/Config/WarioWorld.ini: key=value lines).
std::map<std::string, std::string> ReadMenuSettings() {
  std::map<std::string, std::string> values;
  if (const auto data = ReadFileBytes(g.user / "Config" / "WarioWorld.ini")) {
    std::istringstream in(*data);
    std::string line;
    while (std::getline(in, line)) {
      if (line.empty() || line[0] == '#') continue;
      const auto eq = line.find('=');
      if (eq != std::string::npos) values[Trim(line.substr(0, eq))] = Trim(line.substr(eq + 1));
    }
  }
  return values;
}

